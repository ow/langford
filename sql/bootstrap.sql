    has_minutes boolean default false,
    has_transcript boolean default false,

    video_url text,
    minutes_url text,
    agenda_url text,
    video_duration_seconds int,
    chair_person_id bigint REFERENCES people(id) ON DELETE SET NULL,
    archive_path text unique,
    summary text,
    embedding halfvec(384),
    meta jsonb,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

CREATE INDEX IF NOT EXISTS idx_meetings_municipality_id ON meetings(municipality_id);
