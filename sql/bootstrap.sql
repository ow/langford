-- 7. MATTERS (Longitudinal topics/bylaws)
CREATE TABLE IF NOT EXISTS matters (
    id bigint generated by default as identity primary key,
    title text not null,
    identifier text unique, -- "Bylaw 1540"
    municipality_id bigint REFERENCES municipalities(id) DEFAULT 1,
    description text,
    plain_english_summary text,
    category text,
    status text default 'Active',
    first_seen date,
    last_seen date,
    geo_location jsonb,
    embedding halfvec(384),
    text_search tsvector GENERATED ALWAYS AS (to_tsvector('english', coalesce(title, '') || ' ' || coalesce(plain_english_summary, description, ''))) STORED,
    meta jsonb,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

CREATE INDEX IF NOT EXISTS idx_matters_municipality_id ON matters(municipality_id);

DROP TRIGGER IF EXISTS set_timestamp_matters ON matters;
CREATE TRIGGER set_timestamp_matters BEFORE UPDATE ON matters FOR EACH ROW EXECUTE PROCEDURE update_timestamp();

